"""Build a single self-contained HTML of IS GeoTech (scripts and icon inlined) → dist/index.html"""
import base64, json, os, re
here = os.path.dirname(os.path.abspath(__file__)); www = os.path.join(here, "www"); out = os.path.join(here, "dist")
# engine bundle for the worker (string), regenerated on every build so it always matches the engine files
eng = "".join(open(os.path.join(www, "js", f), encoding="utf-8").read() + "\n" for f in ["gcore.js", "gpile.js", "gfe.js", "worker.js"])
eng = eng.replace("if (typeof module !== \"undefined\") module.exports = GC;", "")
open(os.path.join(www, "js", "engine-src.js"), "w", encoding="utf-8").write("/* generated by build.py — do not edit */\nvar GT_ENGINE_SRC = " + json.dumps(eng) + ";\n")
html = open(os.path.join(www, "index.html"), encoding="utf-8").read()
icon = "data:image/png;base64," + base64.b64encode(open(os.path.join(www, "icon-192.png"), "rb").read()).decode()
html = html.replace('<link rel="manifest" href="manifest.webmanifest">', "").replace('href="icon-192.png"', 'href="' + icon + '"').replace('src="icon-192.png"', 'src="' + icon + '"')
def inline(m):
    js = open(os.path.join(www, m.group(1)), encoding="utf-8").read().replace("</script", "<\\/script")
    return "<script>\n" + js + "\n</script>"
html = re.sub(r'<script src="([^"]+)"></script>', inline, html)
# fonts and reference charts as data URIs so the single file works offline anywhere
def font(m):
    f = m.group(1); mime = "font/otf" if f.endswith(".otf") else "font/ttf"
    return "url(data:" + mime + ";base64," + base64.b64encode(open(os.path.join(www, f), "rb").read()).decode() + ")"
html = re.sub(r'url\((fonts/[^)]+)\)', font, html)
imgs = {os.path.splitext(f)[0]: "data:image/png;base64," + base64.b64encode(open(os.path.join(www, "img", f), "rb").read()).decode() for f in sorted(os.listdir(os.path.join(www, "img"))) if f.endswith(".png")}
html = html.replace("<script>", "<script>window.GT_IMG = " + json.dumps(imgs) + ";</script>\n<script>", 1)
os.makedirs(out, exist_ok=True)
open(os.path.join(out, "index.html"), "w", encoding="utf-8").write(html)
print("dist/index.html", len(html))
